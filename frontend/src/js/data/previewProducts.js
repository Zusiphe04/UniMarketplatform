export function filterPreviewProducts(products, query, category) {
  const normalizedQuery = query.trim().toLocaleLowerCase('en-ZA');

  return products.filter((product) => {
    const matchesCategory = !category || product.category === category;
    const searchable = [
      product.title,
      product.description,
      product.brand,
      product.model,
      product.storage,
      product.memory,
      product.processor,
      product.screenSize,
      product.color,
      product.size,
    ].filter(Boolean).join(' ').toLocaleLowerCase('en-ZA');
    const matchesQuery = !normalizedQuery || searchable.includes(normalizedQuery);
    return matchesCategory && matchesQuery;
  });
}
